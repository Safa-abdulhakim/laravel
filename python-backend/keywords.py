def extract_keywords(text: str, label: str) -> list[str]:
    """
    يبحث عن الكلمات المفتاحية الموجودة فعلاً في النص

    الخوارزمية:
      1. يفحص جميع الكلمات في القوائم
      2. يرجع الكلمات الموجودة في النص
      3. إذا ما وُجد شيء → يرجع أهم 3 كلمات من تصنيف النتيجة
    """
    found: list[str] = []

    # ابحث في كل القوائم
    for words_list in KEYWORDS.values():
        for word in words_list:
            if word in text and word not in found:
                found.append(word)

    # Fallback: إذا ما لقينا شي، رجّع أهم كلمات التصنيف
    if not found:
        found = KEYWORDS.get(label, [])[:3]

    return found
